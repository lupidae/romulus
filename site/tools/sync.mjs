#!/usr/bin/env node
// Brings the app's design tokens and fonts into the static site, so the
// homepage and the app cannot drift apart:
//
//   public/tokens.css   the raw light and dark values of web/src/styles/globals.css,
//                       plus its radii, fonts and easing curves
//   public/fonts/       the latin subsets of the app's two variable fonts, and their licenses
//
//   node tools/sync.mjs           write them
//   node tools/sync.mjs --check   exit 1 if they are stale (CI)
//
// The site has no build step, so this runs by hand after a token change in
// the app, and the check keeps everyone honest.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const web = join(site, "../web");
const check = process.argv.includes("--check");

// The app imports these packages in globals.css; the site self-hosts their
// latin files. Inter's opsz file carries the optical size axis too, so large
// headings get Inter Display's tighter shapes on their own.
// Both are under the SIL Open Font License, which travels with the files.
const fonts = [
  ["@fontsource-variable/inter/files/inter-latin-opsz-normal.woff2", "inter-latin-opsz-normal.woff2"],
  ["@fontsource-variable/inter/LICENSE", "LICENSE-inter.txt"],
  [
    "@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2",
    "jetbrains-mono-latin-wght-normal.woff2",
  ],
  ["@fontsource-variable/jetbrains-mono/LICENSE", "LICENSE-jetbrains-mono.txt"],
];

/** The body of the first `selector { … }` block at or after `from`. */
function block(css, selector, from = 0) {
  const start = css.indexOf(`${selector} {`, from);
  if (start < 0) throw new Error(`globals.css: no "${selector} {" block`);
  let depth = 0;
  for (let i = css.indexOf("{", start); i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) return css.slice(css.indexOf("{", start) + 1, i);
  }
  throw new Error(`globals.css: "${selector}" is not closed`);
}

/** Declarations whose property matches `pattern`, one per entry, comments dropped. */
function declarations(body, pattern) {
  const out = [];
  const text = body.replace(/\/\*[\s\S]*?\*\//g, "");
  for (const decl of text.split(";")) {
    const trimmed = decl.trim().replace(/\s+/g, " ");
    const name = trimmed.split(":")[0];
    if (trimmed && pattern.test(name)) out.push(`  ${trimmed};`);
  }
  return out;
}

// The raw values live in globals.css, the Tailwind theme in theme.css (which
// globals.css imports): read as one, in that order.
const globals = [
  await readFile(join(web, "src/styles/globals.css"), "utf8"),
  await readFile(join(web, "src/styles/theme.css"), "utf8"),
].join("\n");
const light = block(globals, ":root");
const dark = block(globals, ".dark");
const theme = block(globals, "@theme inline");
const motion = block(globals, ":root", globals.indexOf(":root {") + 1);

const indent = (body, by) =>
  body
    .trim()
    .split("\n")
    .map((line) => (line.trim() ? by + line.trim() : ""))
    .join("\n");

const tokens = `/*
 * Generated by site/tools/sync.mjs from web/src/styles/globals.css: the app's
 * own tokens, so the homepage and the app are one brand. Do not edit; change
 * the app's tokens and run \`npm --prefix site run sync\`.
 *
 * Theme: the class on <html> wins (.light or .dark, set before first paint
 * from the "romulus-theme" choice the app also reads); without one, the
 * system preference decides, with or without JavaScript.
 */
:root {
${indent(light, "  ")}

${[
  ...declarations(theme, /^--(font-sans|font-mono|radius-[a-z]+)$/),
  ...declarations(theme, /^--ease-/),
  ...declarations(motion, /^--duration-/),
].join("\n")}
}

.dark {
${indent(dark, "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not(.light) {
${indent(dark, "    ")}
  }
}
`;

let stale = [];
const out = join(site, "public/tokens.css");
if (check) {
  const current = existsSync(out) ? await readFile(out, "utf8") : "";
  if (current !== tokens) stale.push("public/tokens.css");
} else {
  await writeFile(out, tokens);
}

await mkdir(join(site, "public/fonts"), { recursive: true });
for (const [from, to] of fonts) {
  const src = join(web, "node_modules", from);
  if (!existsSync(src)) throw new Error(`${src} is missing: run \`npm ci --prefix web\` first`);
  const bytes = await readFile(src);
  const dest = join(site, "public/fonts", to);
  if (check) {
    if (!existsSync(dest) || !bytes.equals(await readFile(dest))) stale.push(`public/fonts/${to}`);
  } else {
    await writeFile(dest, bytes);
  }
}

if (stale.length) {
  console.error(`sync: stale ${stale.join(", ")}; run \`npm --prefix site run sync\` and commit`);
  process.exit(1);
}
if (!check) console.log("sync: wrote public/tokens.css and public/fonts/");

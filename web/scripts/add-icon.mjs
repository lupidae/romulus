#!/usr/bin/env node
// Adds Iconoir icons as owned React components in src/components/icons.
//
//   npm run icons:add -- database git-branch
//
// The icon set is locked to Iconoir (.library.json, chosen with the design
// system): one stroke style across the product. Icons are inlined at build
// time, never fetched at runtime, so nothing flashes on first paint. This is
// what the better-design `install-icons` tool does, as a script anyone can run.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../src/components/icons");
const manifestPath = join(dir, ".library.json");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));

const requested = process.argv.slice(2);
const names = [...new Set([...manifest.icons, ...requested])].sort();

const res = await fetch(
  `https://api.iconify.design/${manifest.prefix}.json?icons=${names.join(",")}`,
);
if (!res.ok) throw new Error(`iconify: HTTP ${res.status}`);
const data = await res.json();
const missing = names.filter((n) => !data.icons?.[n]);
if (missing.length) {
  console.error(`unknown ${manifest.prefix} icons: ${missing.join(", ")}`);
  process.exit(1);
}

const pascal = (name) =>
  name
    .split("-")
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");

// SVG attributes → JSX props.
const jsx = (body) =>
  body.replace(/([a-z]+)-([a-z])([a-z]*)=/g, (_, a, b, c) => `${a}${b.toUpperCase()}${c}=`);

for (const name of names) {
  const icon = data.icons[name];
  const width = icon.width ?? data.width ?? 24;
  const height = icon.height ?? data.height ?? 24;
  const component = `${pascal(name)}Icon`;
  const source = `// Iconoir "${name}" (generated by scripts/add-icon.mjs, do not edit)
import type { SVGProps } from "react";

export function ${component}(props: SVGProps<SVGSVGElement>) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 ${width} ${height}"
      width="1em"
      height="1em"
      aria-hidden={props["aria-label"] ? undefined : true}
      focusable="false"
      {...props}
    >
      ${jsx(icon.body)}
    </svg>
  );
}
`;
  await writeFile(join(dir, `${name}.tsx`), source);
}

const index = `// Iconoir icons, generated by scripts/add-icon.mjs. Add one with
// \`npm run icons:add -- <name>\` (names: https://icon-sets.iconify.design/iconoir/).
// Never mix in another icon library.
${names.map((n) => `export { ${pascal(n)}Icon } from "./${n}";`).join("\n")}
`;
await writeFile(join(dir, "index.ts"), index);
await writeFile(manifestPath, JSON.stringify({ ...manifest, icons: names }, null, 2) + "\n");
console.log(`${names.length} icons in src/components/icons`);

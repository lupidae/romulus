-- Identity, serial and generated columns.
CREATE TABLE invoices (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    legacy_id     integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1) UNIQUE,
    number        serial NOT NULL,
    subtotal      numeric(12, 2) NOT NULL,
    tax_rate      numeric(5, 4) NOT NULL DEFAULT 0.2,
    tax           numeric(12, 2) GENERATED ALWAYS AS (round(subtotal * tax_rate, 2)) STORED,
    total         numeric(12, 2) GENERATED ALWAYS AS (subtotal + round(subtotal * tax_rate, 2)) STORED,
    issued_on     date NOT NULL DEFAULT CURRENT_DATE,
    due_on        date GENERATED ALWAYS AS (issued_on + 30) STORED,
    title         text NOT NULL,
    body          text,
    search        tsvector GENERATED ALWAYS AS (
                      setweight(to_tsvector('english', coalesce(title, '')), 'A') ||
                      setweight(to_tsvector('english', coalesce(body, '')), 'B')
                  ) STORED
);
CREATE INDEX invoices_search_idx ON invoices USING gin (search);
CREATE INDEX invoices_due_idx ON invoices (due_on) INCLUDE (total);

CREATE SEQUENCE ticket_numbers START 500 INCREMENT 5;
CREATE TABLE tickets (
    number     integer NOT NULL DEFAULT nextval('ticket_numbers') PRIMARY KEY,
    invoice_id bigint REFERENCES invoices (id) ON DELETE SET NULL
);
ALTER SEQUENCE ticket_numbers OWNED BY tickets.number;

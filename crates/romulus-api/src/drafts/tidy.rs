//! Tidy: the draft's SQL rewritten in remus's canonical form, for whoever
//! wants a clean file again after graph edits piled up (docs/MVP.md "Schema
//! edits from the graph append SQL").
//!
//! The canonical text is `render_sql` of the model the current text
//! compiles to, so Tidy needs a text that compiles (422 `compile_failed`
//! otherwise). It must mean exactly the same schema: the rewrite is
//! compiled too, and refused (422 `tidy_unsafe`) if its model differs, as
//! it would for what remus does not write back (foreign tables…). `--` line
//! comments are lost; `COMMENT ON` is part of the model and kept.
//!
//! The rewrite reaches the doc as the smallest edit ([`patch`]), in one
//! transaction, so collaborators' carets and concurrent typing elsewhere
//! survive it; the same transaction notes it (`Roots::note_rewrite`), and
//! every client drops its undo history. Someone typing between reading the text and applying the
//! edit makes the room refuse it; Tidy then starts over, a few times, before
//! answering 409 `draft_changed`.

use axum::extract::State;
use romulus_sandbox::render_sql;
use serde::{Deserialize, Serialize};
use serde_json::json;
use utoipa::ToSchema;
use uuid::Uuid;

use super::{
    find, not_open,
    publish::{compiled, hub_error},
};
use crate::{
    ApiError, ApiResult, AppState,
    auth::{Member, min},
    collab::{compile::sha256_hex, patch, protocol::LiveStatus, room::RewriteError},
    databases,
    domain::{DraftMode, DraftStatus, Schema},
    error::ErrorBody,
    extract::{Json, Path},
};

/// Attempts before giving up on a draft that keeps changing.
const ATTEMPTS: usize = 3;

/// What Tidy did.
#[derive(Debug, Serialize, Deserialize, ToSchema)]
pub struct Tidied {
    /// Whether the SQL changed (false: it was tidy already).
    pub changed: bool,
    /// SHA-256 of the SQL as Tidy left it.
    pub sha256: String,
}

/// The canonical SQL of a model, without remus's header comment (a draft is
/// not a dump of a database).
pub fn canonical_sql(model: &Schema) -> String {
    let sql = render_sql(model);
    let body = if sql.starts_with("-- Schema DDL generated by remus") {
        let mut rest = sql.as_str();
        while let Some(line_end) = rest.find('\n') {
            if !rest.starts_with("--") {
                break;
            }
            rest = &rest[line_end + 1..];
        }
        rest.trim_start_matches('\n')
    } else {
        sql.as_str()
    };
    let mut out = body.trim_end().to_owned();
    if !out.is_empty() {
        out.push('\n');
    }
    out
}

/// Rewrites the draft's SQL in canonical form.
#[utoipa::path(
    post,
    path = "/orgs/{org}/databases/{db}/drafts/{id}/tidy",
    operation_id = "tidy_draft",
    tag = "drafts",
    params(("org" = String, Path), ("db" = String, Path), ("id" = Uuid, Path)),
    responses(
        (status = 200, body = Tidied),
        (status = 403, body = ErrorBody),
        (status = 404, body = ErrorBody),
        (status = 409, description = "`draft_changed` (it kept changing: try again), `draft_published`, `draft_busy` (being published), `migration_mode` (the draft is edited as a migration)", body = ErrorBody),
        (status = 422, description = "`compile_failed` (the SQL has errors, `details.diagnostics`), `tidy_unsafe` (the canonical form would change the schema)", body = ErrorBody),
        (status = 429, body = ErrorBody),
        (status = 503, description = "The compiler is unavailable", body = ErrorBody),
    )
)]
pub(super) async fn tidy(
    member: Member<min::Developer>,
    Path((_, db_slug, id)): Path<(String, String, Uuid)>,
    State(state): State<AppState>,
) -> ApiResult<Json<Tidied>> {
    let database = databases::find(&state.db, member.org.id, &db_slug).await?;
    let row = find(&state.db, &database, id).await?;
    if row.status != DraftStatus::Open {
        return Err(not_open(row.status));
    }
    state.limits.compile.check(member.user.id)?;
    state.limits.database_compiles.check(database.id)?;

    for _ in 0..ATTEMPTS {
        let content = state.collab.content(id).await.map_err(hub_error)?;
        if content.mode != DraftMode::Schema {
            return Err(migration_mode());
        }
        let model = match compiled(&state.collab, &content).await? {
            (Some(model), _) => model,
            (None, diagnostics) => {
                return Err(ApiError::Unprocessable {
                    code: "compile_failed",
                    message: "The SQL has errors. Fix them before tidying.".into(),
                    details: Some(json!({ "diagnostics": diagnostics })),
                });
            }
        };
        let sql = canonical_sql(&model);
        if sql == content.sql {
            return Ok(Json(Tidied {
                changed: false,
                sha256: sha256_hex(&sql),
            }));
        }
        // The rewrite must be the same schema, or it is no tidying.
        let check = state.collab.compiler().compile(&sql).await?;
        if check.model.as_ref() != Some(&model) {
            tracing::warn!(
                draft = %id,
                compiles = check.model.is_some(),
                "tidy: the canonical SQL is another schema; refused",
            );
            return Err(ApiError::Unprocessable {
                code: "tidy_unsafe",
                message: "Tidy cannot rewrite this SQL without changing the schema: it defines \
                          something the canonical form does not write (a foreign table, for \
                          one). Nothing was changed."
                    .into(),
                details: None,
            });
        }
        let old = content.sql.clone();
        let new = sql.clone();
        let edits = tokio::task::spawn_blocking(move || patch::changes(&old, &new))
            .await
            .map_err(ApiError::internal)?;
        match state
            .collab
            .rewrite(id, sha256_hex(&content.sql), edits, "tidy")
            .await
            .map_err(hub_error)?
        {
            Ok(changed) => {
                tracing::info!(draft = %id, changed, "draft tidied");
                return Ok(Json(Tidied {
                    changed,
                    sha256: sha256_hex(&sql),
                }));
            }
            Err(RewriteError::Changed) => {}
            Err(RewriteError::NotOpen(status)) => return Err(closed(status)),
            Err(RewriteError::Mode(_)) => return Err(migration_mode()),
        }
    }
    Err(ApiError::Conflict {
        code: "draft_changed",
        message: "The SQL kept changing while it was being tidied. Try again when typing pauses."
            .into(),
    })
}

/// 409 `migration_mode`: the migration is the source, the SQL is derived.
fn migration_mode() -> ApiError {
    ApiError::Conflict {
        code: "migration_mode",
        message: "This draft is edited as a migration: its schema SQL is derived, there is nothing to tidy.".into(),
    }
}

fn closed(status: LiveStatus) -> ApiError {
    match status {
        LiveStatus::Publishing | LiveStatus::Updating => ApiError::Conflict {
            code: "draft_busy",
            message: "Someone is publishing or updating this draft right now.".into(),
        },
        LiveStatus::Published => not_open(DraftStatus::Published),
        LiveStatus::Open | LiveStatus::Deleted => not_open(DraftStatus::Deleted),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_canonical_sql_has_no_remus_header() {
        let model = Schema::from_json(remus_core::fixtures::SHOWCASE).unwrap();
        let sql = canonical_sql(&model);
        assert!(!sql.starts_with("--"), "{}", &sql[..200]);
        assert!(sql.ends_with(";\n"));
        assert!(!sql.contains("generated by remus"));
        // Comments on objects are statements, and stay.
        assert!(sql.contains("COMMENT ON"));
    }

    #[test]
    fn an_empty_model_is_an_empty_text() {
        let mut model = Schema::from_json(remus_core::fixtures::SHOWCASE).unwrap();
        model.entities.clear();
        model.enums.clear();
        model.domains.clear();
        model.composites.clear();
        model.partitions.clear();
        model.extensions.clear();
        assert_eq!(canonical_sql(&model), "");
    }
}

//! The plan, before any row: which tables load and in what order, how many
//! rows each gets, and how every column is filled. Built once from the
//! remus model by [`analyze`]; rows are then generated from it on demand.

use std::collections::{BTreeMap, HashMap, HashSet};

use remus_core::{
    Schema,
    model::{ConstraintKind, Entity, EntityKind, Generated, Identity},
};
use serde::{Deserialize, Serialize};

use crate::{
    Options, Profile, Size,
    checks::{self, Bounds, Pattern},
    expr::{self, Expr},
    generate,
    heuristics::{self, Heuristic},
    partition::{self, Leaf},
    rng::{self, Key, Permutation},
    types::{Base, Type, Types},
    value::{DAY, V, days_from_civil},
};

/// "Now" for generated timestamps: fixed per generator version, so the
/// same seed gives the same rows on any day (docs/playground.md,
/// "Determinism").
pub const ANCHOR_DAY: (i64, u32, u32) = (2026, 10, 1);

pub fn anchor() -> i64 {
    let (y, m, d) = ANCHOR_DAY;
    days_from_civil(y, m, d) * DAY
}

/// A table's role in the foreign key graph, which sets its size.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Role {
    /// Referenced, referencing nothing, narrow: statuses, countries, rooms.
    Lookup,
    Entity,
    /// Referencing others and referenced by none (or partitioned): the
    /// bulk of the rows.
    Event,
}

/// How a column gets its values.
#[derive(Debug, Clone)]
pub enum Fill {
    /// Not written: Postgres fills it.
    Database(&'static str),
    /// `start + row`: a key written explicitly (identity or serial that a
    /// foreign key points at), its sequence moved past it afterwards.
    Sequence { start: i128 },
    /// One column of a foreign key: the parent row's value.
    Foreign { fk: usize, position: usize },
    /// A partition key column: inside the row's leaf.
    Partition,
    /// Generated by heuristic or type.
    Value,
    /// Always NULL: a type it cannot produce, in a nullable column.
    Null,
}

#[derive(Debug, Clone)]
#[allow(clippy::struct_excessive_bools)]
pub struct Col {
    pub name: String,
    pub ty: Type,
    /// The type as the model prints it: the cast target in the load.
    pub type_text: String,
    pub not_null: bool,
    pub fill: Fill,
    pub null_rate: f64,
    pub key: Key,
    pub heuristic: Option<Heuristic>,
    pub bounds: Bounds,
    /// Distinct in every row (a unique set's chosen column).
    pub unique: bool,
    /// Never overlapping from row to row (`EXCLUDE … WITH &&`).
    pub disjoint: bool,
    /// Same value whatever the redraw: foreign keys read it.
    pub stable: bool,
    pub cents: bool,
    /// A constant default, mixed into the values.
    pub default: Option<V>,
    /// Must come after these columns' values: (column, strictly).
    pub after: Vec<(usize, bool)>,
    /// `pg_input_is_valid` before the cast in the load: types and domains
    /// whose input Postgres must judge.
    pub validate: bool,
    /// Domain CHECKs with a shape the bounds do not hold, evaluated per row.
    pub domain_checks: Vec<Expr>,
    /// `GENERATED ALWAYS AS IDENTITY`: written with `OVERRIDING SYSTEM VALUE`.
    pub identity_always: bool,
    /// A generated column's expression, and the columns it reads.
    pub expression: Option<String>,
    pub expression_columns: Vec<String>,
    /// The expression parsed, when the evaluator can compute it: a row
    /// whose generated value would not fit the column is drawn again.
    pub expression_expr: Option<Expr>,
}

impl Col {
    pub fn written(&self) -> bool {
        !matches!(self.fill, Fill::Database(_))
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FkMode {
    /// Skewed fan-out over the parent's rows.
    Skewed,
    /// Each parent at most once (the FK's columns are unique here).
    OneToOne,
    /// A self-reference: an earlier row (a tree).
    Tree,
    /// A self-reference that is unique: the previous row (a chain).
    Chain,
    /// Drawn with other columns of a unique set: see [`Combo`].
    Combo { combo: usize, part: usize },
}

#[derive(Debug, Clone)]
#[allow(clippy::struct_excessive_bools)]
pub struct Fk {
    pub name: String,
    pub definition: String,
    pub columns: Vec<usize>,
    pub parent: Option<usize>,
    pub parent_columns: Vec<usize>,
    pub nullable: bool,
    /// Loaded NULL, then set by an UPDATE once the parent is loaded (a
    /// cycle, a nullable self-reference).
    pub deferred: bool,
    /// Checked in the load's WHERE (not for a self-reference written
    /// directly: Postgres checks it at the end of the statement).
    pub exists_check: bool,
    pub mode: FkMode,
    pub null_rate: f64,
    pub key: Key,
    pub stable: bool,
    pub match_full: bool,
    pub comment: Option<String>,
}

/// A unique set with no column that can be told apart row by row
/// (`PRIMARY KEY (org_id, user_id)`): its columns are drawn together, as
/// the digits of one number below the product of their choices, taken
/// from a permutation (no repeats).
#[derive(Debug, Clone)]
pub struct Combo {
    pub parts: Vec<ComboPart>,
    pub space: u64,
    pub perm: Permutation,
}

#[derive(Debug, Clone)]
pub enum ComboPart {
    Fk(usize),
    Column { column: usize, values: Vec<V> },
}

impl ComboPart {
    pub fn radix(&self, tables: &[Table], fks: &[Fk]) -> u64 {
        match self {
            ComboPart::Fk(f) => fks[*f].parent.map_or(0, |p| tables[p].rows),
            ComboPart::Column { values, .. } => values.len() as u64,
        }
    }
}

#[derive(Debug, Clone)]
pub struct Check {
    pub name: String,
    /// The expression as Postgres printed it (the load's WHERE).
    pub sql: String,
    pub expr: Option<Expr>,
    /// Satisfied by construction (every conjunct is a shape).
    pub shaped: bool,
    pub columns: Vec<String>,
}

#[derive(Debug, Clone)]
pub struct NonNullGroup {
    pub columns: Vec<usize>,
    pub min: usize,
    pub max: usize,
}

/// Something the plan could not do as the schema asks, for the report.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Fallback {
    pub kind: FallbackKind,
    /// The constraint (or column) concerned.
    pub constraint: Option<String>,
    pub reason: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum FallbackKind {
    /// Fewer rows than the preset: what the keys or parents can hold.
    Capped,
    /// A CHECK evaluated on each row: a row breaking it is drawn again.
    Redrawn,
    /// Left to Postgres: rows breaking it are dropped.
    Judged,
    /// Not built as the schema asks (duplicates, NULLs where a value would
    /// do): the load drops what Postgres refuses.
    NotBuilt,
    /// Parts of the schema that get no rows.
    NoRows,
}

impl Fallback {
    fn new(kind: FallbackKind, constraint: Option<String>, reason: impl Into<String>) -> Self {
        Self {
            kind,
            constraint,
            reason: reason.into(),
        }
    }
}

#[derive(Debug, Clone)]
pub struct Table {
    pub schema: String,
    pub name: String,
    pub role: Role,
    pub rows: u64,
    pub columns: Vec<Col>,
    pub fks: Vec<Fk>,
    pub checks: Vec<Check>,
    pub patterns: HashMap<(String, bool, bool), Pattern>,
    pub non_nulls: Vec<NonNullGroup>,
    pub combos: Vec<Combo>,
    pub leaves: Vec<Leaf>,
    pub leaf_weights: u32,
    /// No `ON CONFLICT`: a deferrable unique cannot be its arbiter.
    pub deferrable_unique: bool,
    pub rls_forced: bool,
    pub key: Key,
    pub perm: Permutation,
    /// Not loaded, and why.
    pub skip: Option<String>,
    pub fallbacks: Vec<Fallback>,
    /// The columns a cycle UPDATE finds its rows by.
    pub update_key: Option<Vec<usize>>,
    /// Columns written explicitly whose sequence must move past them.
    pub sequences: Vec<(usize, Option<String>)>,
    pub staging: String,
    pub bytes_per_row: u64,
    pub partitioned: bool,
}

impl Table {
    pub fn qualified(&self) -> String {
        format!("{}.{}", self.schema, self.name)
    }

    pub fn column(&self, name: &str) -> Option<usize> {
        self.columns.iter().position(|c| c.name == name)
    }
}

/// Tables loaded together: one, or a cycle of foreign keys.
#[derive(Debug, Clone)]
pub struct Unit {
    pub tables: Vec<usize>,
    /// A cycle `NOT NULL` both ways: the FK left out while loading, put
    /// back after (table, fk).
    pub held: Vec<(usize, usize)>,
}

#[derive(Debug, Clone)]
pub struct Model {
    pub tables: Vec<Table>,
    pub units: Vec<Unit>,
    pub matviews: Vec<String>,
    pub staging: String,
    pub options: Options,
    pub anchor: i64,
    /// Relations not loaded: (name, why).
    pub skipped: Vec<(String, String)>,
}

fn quote(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

pub fn qualified_sql(schema: &str, name: &str) -> String {
    format!("{}.{}", quote(schema), quote(name))
}

/// Whether a default expression is a constant (no call, no keyword).
fn constant_default(e: &Expr) -> bool {
    let mut constant = true;
    e.walk(&mut |x| {
        if matches!(
            x,
            Expr::Func(..) | Expr::Keyword(_) | Expr::Col(_) | Expr::Unknown
        ) {
            constant = false;
        }
    });
    constant
}

/// The value of a constant default for a column of type `ty`.
fn default_value(e: &Expr, ty: &Type) -> Option<V> {
    if !constant_default(e) {
        return None;
    }
    if ty.array {
        let elem = Type {
            array: false,
            ..ty.clone()
        };
        return match e.uncast() {
            Expr::Array(items) => items
                .iter()
                .map(|x| checks::literal(x, Some(&elem)))
                .collect::<Option<Vec<_>>>()
                .map(V::Array),
            Expr::Lit(expr::Lit::Str(s)) if s == "{}" => Some(V::Array(Vec::new())),
            _ => None,
        };
    }
    let v = checks::literal(e, Some(ty))?;
    let v = match (&ty.base, v) {
        (Base::Bit(_) | Base::VarBit(_), V::Text(s)) => V::Raw(s),
        (_, v) => v,
    };
    generate::conform(v, ty)
}

/// `nextval('public.t_id_seq'::regclass)` → the sequence: `None` for
/// another default, `Some(None)` when the sequence is not a literal.
#[allow(clippy::option_option)]
fn nextval(default: &str) -> Option<Option<String>> {
    let e = expr::parse(default)?;
    match e {
        Expr::Func(name, args) if name == "nextval" || name == "pg_catalog.nextval" => {
            Some(args.first().and_then(|a| match a.uncast() {
                Expr::Lit(expr::Lit::Str(s)) => Some(s.clone()),
                _ => None,
            }))
        }
        _ => None,
    }
}


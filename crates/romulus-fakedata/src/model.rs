/// Builds the plan.
#[allow(clippy::too_many_lines)]
pub fn analyze(model: &Schema, options: &Options, counts: &BTreeMap<String, u64>) -> Model {
    let seed = options.seed;
    let types = Types { model };
    let mut skipped = Vec::new();
    let provided = |schema: &str, name: &str| {
        model.extensions.iter().any(|x| {
            x.schema == schema
                && romulus_migration::EXTENSION_OBJECTS
                    .iter()
                    .any(|(e, o)| *e == x.name && *o == name)
        })
    };
    let partition_children: HashSet<(String, String)> = model
        .partitions
        .iter()
        .map(|p| (p.child_schema.clone(), p.child.clone()))
        .collect();
    let mut entities: Vec<&Entity> = Vec::new();
    for e in &model.entities {
        let name = format!("{}.{}", e.schema, e.name);
        match e.kind {
            EntityKind::Table | EntityKind::PartitionedTable => {}
            EntityKind::ForeignTable => {
                skipped.push((name, "a foreign table: its rows live elsewhere".to_owned()));
                continue;
            }
            EntityKind::View | EntityKind::MaterializedView => continue,
        }
        if provided(&e.schema, &e.name) {
            skipped.push((name, "provided by an extension".to_owned()));
            continue;
        }
        if partition_children.contains(&(e.schema.clone(), e.name.clone())) {
            continue;
        }
        entities.push(e);
    }
    entities.sort_by(|a, b| (&a.schema, &a.name).cmp(&(&b.schema, &b.name)));
    let index: HashMap<(String, String), usize> = entities
        .iter()
        .enumerate()
        .map(|(i, e)| ((e.schema.clone(), e.name.clone()), i))
        .collect();
    // A schema of its own, under a name no schema in the model has, with a
    // suffix from the seed: an empty schema the model cannot list (remus
    // lists schemas through their objects) will not hold that name.
    let schemas: HashSet<&str> = model
        .entities
        .iter()
        .map(|e| e.schema.as_str())
        .chain(model.enums.iter().map(|e| e.schema.as_str()))
        .chain(model.domains.iter().map(|d| d.schema.as_str()))
        .chain(model.composites.iter().map(|c| c.schema.as_str()))
        .chain(model.extensions.iter().map(|x| x.schema.as_str()))
        .collect();
    let key = rng::key(seed, &["#staging"]);
    let suffix = format!("{:02x}{:02x}{:02x}{:02x}", key[0], key[1], key[2], key[3]);
    let mut staging = format!("romulus_fakedata_{suffix}");
    let mut n = 1;
    while schemas.contains(staging.as_str()) {
        staging = format!("romulus_fakedata_{suffix}_{n}");
        n += 1;
    }

    // Tables, columns, constraints.
    let mut tables: Vec<Table> = Vec::new();
    for (ti, e) in entities.iter().enumerate() {
        let mut t = table(e, ti, seed, &types, model);
        let fks = e
            .constraints
            .iter()
            .filter(|c| c.kind == ConstraintKind::ForeignKey)
            .filter_map(|c| {
                let columns: Option<Vec<usize>> = c.columns.iter().map(|n| t.column(n)).collect();
                let columns = columns?;
                let parent = c
                    .target()
                    .and_then(|r| index.get(&(r.schema.clone(), r.name.clone())).copied());
                let parent_columns = match parent {
                    Some(p) => c
                        .ref_columns
                        .iter()
                        .map(|n| entities[p].columns.iter().position(|x| &x.name == n))
                        .collect::<Option<Vec<_>>>()?,
                    None => Vec::new(),
                };
                let nullable = columns.iter().all(|&i| !t.columns[i].not_null);
                Some(Fk {
                    name: c.name.clone(),
                    definition: c.definition.clone(),
                    columns,
                    parent,
                    parent_columns,
                    nullable,
                    deferred: false,
                    exists_check: true,
                    mode: FkMode::Skewed,
                    null_rate: 0.0,
                    key: rng::key(seed, &[&e.schema, &e.name, "#fk", &c.name]),
                    stable: false,
                    match_full: c.definition.contains("MATCH FULL"),
                    comment: c.comment.clone(),
                })
            })
            .collect::<Vec<_>>();
        for c in &e.constraints {
            if c.kind == ConstraintKind::ForeignKey && !fks.iter().any(|f| f.name == c.name) {
                t.fallbacks.push(Fallback::new(
                    FallbackKind::NotBuilt,
                    Some(c.name.clone()),
                    "a foreign key whose columns the model does not list: left to Postgres",
                ));
            }
        }
        t.fks = fks;
        tables.push(t);
    }

    // Load order: strongly connected components, parents first.
    let (units, deferred) = order(&tables);
    for (t, f) in &deferred {
        tables[*t].fks[*f].deferred = true;
    }
    for (ti, t) in tables.iter_mut().enumerate() {
        for f in &mut t.fks {
            if f.parent == Some(ti) {
                let unique = t_unique_set(
                    &t_sets(&entities[ti].constraints, &entities[ti].indexes).0,
                    &f.columns,
                    &t.columns,
                );
                f.mode = if unique { FkMode::Chain } else { FkMode::Tree };
                if f.nullable {
                    f.deferred = true;
                } else {
                    f.exists_check = false;
                }
            }
        }
    }

    // Roles, then sizes.
    let mut referenced = vec![0usize; tables.len()];
    for (ti, t) in tables.iter().enumerate() {
        for f in &t.fks {
            if let Some(p) = f.parent
                && p != ti
            {
                referenced[p] += 1;
            }
        }
    }
    for (ti, t) in tables.iter_mut().enumerate() {
        let out = t
            .fks
            .iter()
            .filter(|f| f.parent.is_some_and(|p| p != ti))
            .count();
        let partitioned = entities[ti].kind == EntityKind::PartitionedTable;
        t.role = if referenced[ti] > 0 && out == 0 && (t.columns.len() <= 4 || lookup_name(&t.name))
        {
            Role::Lookup
        } else if (out > 0 && referenced[ti] == 0)
            || partitioned
            || (referenced[ti] == 0 && event_name(&t.name))
        {
            Role::Event
        } else {
            Role::Entity
        };
        let h = rng::mix(u64::from_le_bytes(t.key[..8].try_into().unwrap_or([0; 8])));
        t.rows = match (options.size, t.role) {
            (Size::Small, Role::Lookup) => 10 + h % 41,
            (Size::Medium, Role::Lookup) => 10 + h % 191,
            (Size::Small, Role::Entity) => 200,
            (Size::Medium, Role::Entity) => 10_000,
            (Size::Small, Role::Event) => 2_000,
            (Size::Medium, Role::Event) => 100_000,
        };
    }
    let cap = match options.size {
        Size::Small => 50_000,
        Size::Medium => 1_000_000,
    };
    // Counts set by hand replace the preset's.
    let set: Vec<bool> = tables
        .iter()
        .map(|t| counts.contains_key(&t.qualified()))
        .collect();
    for t in &mut tables {
        if let Some(&n) = counts.get(&t.qualified()) {
            t.rows = n;
        }
    }
    // The cap: the preset's entities and events shrink first, then, when
    // the counts set by hand pass it alone, everything.
    let sum = |pick: &dyn Fn(usize, &Table) -> bool| -> u64 {
        tables
            .iter()
            .enumerate()
            .filter(|(i, t)| pick(*i, t))
            .map(|(_, t)| t.rows)
            .sum()
    };
    let by_hand = sum(&|i, _| set[i]);
    let lookups = sum(&|i, t| !set[i] && t.role == Role::Lookup);
    let rest = sum(&|i, t| !set[i] && t.role != Role::Lookup);
    if by_hand + lookups + rest > cap {
        if by_hand + lookups <= cap && rest > 0 {
            let factor = (cap - by_hand - lookups) as f64 / rest as f64;
            for (i, t) in tables.iter_mut().enumerate() {
                if !set[i] && t.role != Role::Lookup {
                    t.rows = ((t.rows as f64 * factor) as u64).max(1);
                }
            }
        } else {
            let factor = cap as f64 / (by_hand + lookups + rest) as f64;
            for (i, t) in tables.iter_mut().enumerate() {
                let before = t.rows;
                t.rows = ((t.rows as f64 * factor) as u64).max(1);
                if set[i] && t.rows < before {
                    t.fallbacks.push(Fallback::new(
                        FallbackKind::Capped,
                        None,
                        format!("rows capped at {}: the counts set by hand pass the size's cap of {cap}", t.rows),
                    ));
                }
            }
        }
        // At least a row per table can round past the cap: the largest
        // table gives the excess back.
        let total: u64 = tables.iter().map(|t| t.rows).sum();
        if total > cap
            && let Some(t) = tables.iter_mut().max_by_key(|t| t.rows)
        {
            t.rows -= (total - cap).min(t.rows.saturating_sub(1));
        }
    }
    if let Some(max) = options.max_rows_per_table {
        for t in &mut tables {
            t.rows = t.rows.min(max);
        }
    }

    // Columns referenced by a foreign key are keys: written and stable.
    let mut referenced_columns: HashSet<(usize, usize)> = HashSet::new();
    for t in &tables {
        for f in &t.fks {
            if let Some(p) = f.parent {
                for &c in &f.parent_columns {
                    referenced_columns.insert((p, c));
                }
            }
        }
    }

    for (ti, e) in entities.iter().enumerate() {
        fill_columns(&mut tables, ti, e, &referenced_columns, options);
    }

    // Sizes capped by what the keys can hold, parents first.
    let load_order: Vec<usize> = units.iter().flat_map(|u| u.tables.clone()).collect();
    for &ti in &load_order {
        cap_rows(&mut tables, ti);
    }
    for t in &mut tables {
        t.perm = Permutation::new(t.rows, &t.key);
        let n = t.rows;
        for combo in &mut t.combos {
            combo.perm = Permutation::new(
                combo.space.max(n),
                &rng::key(seed, &[&t.schema, &t.name, "#combo"]),
            );
        }
    }

    // Materialized views, in dependency order.
    let mut matviews: Vec<&Entity> = model
        .entities
        .iter()
        .filter(|e| e.kind == EntityKind::MaterializedView)
        .collect();
    matviews.sort_by(|a, b| (&a.schema, &a.name).cmp(&(&b.schema, &b.name)));
    let mut ordered: Vec<String> = Vec::new();
    let mut left: Vec<&Entity> = matviews;
    while !left.is_empty() {
        let ready = left
            .iter()
            .position(|m| {
                m.depends_on.iter().all(|d| {
                    !left
                        .iter()
                        .any(|o| o.schema == d.schema && o.name == d.name)
                        || ordered.contains(&qualified_sql(&d.schema, &d.name))
                })
            })
            .unwrap_or(0);
        let m = left.remove(ready);
        ordered.push(qualified_sql(&m.schema, &m.name));
    }

    Model {
        tables,
        units,
        matviews: ordered,
        staging,
        options: options.clone(),
        anchor: anchor(),
        skipped,
    }
}

/// (columns, NULLS NOT DISTINCT, deferrable, name) of every PK, UNIQUE and
/// unique index.
/// The column a unique index key keeps distinct values of: a column, or
/// one under a cast, `lower` or `upper` (the row number the generator
/// writes survives them). Other expressions (`date_trunc('day', ts)`) can
/// map distinct values to one.
fn key_column(e: &Expr) -> Option<String> {
    match e {
        Expr::Col(c) => Some(c.clone()),
        Expr::Cast(inner, _) => key_column(inner),
        Expr::Func(name, args) if args.len() == 1 => {
            let bare = name.rsplit('.').next().unwrap_or(name);
            matches!(bare, "lower" | "upper")
                .then(|| key_column(&args[0]))
                .flatten()
        }
        _ => None,
    }
}

/// (columns, NULLS NOT DISTINCT, deferrable, name) of every PK, UNIQUE and
/// unique index whose keys the generator can keep distinct, and the names
/// of the unique indexes it cannot (expressions).
#[allow(clippy::type_complexity)]
fn t_sets(
    constraints: &[remus_core::model::Constraint],
    indexes: &[remus_core::model::Index],
) -> (Vec<(Vec<String>, bool, bool, String)>, Vec<String>) {
    let mut out = Vec::new();
    let mut untrusted = Vec::new();
    for c in constraints {
        if matches!(c.kind, ConstraintKind::PrimaryKey | ConstraintKind::Unique) {
            out.push((
                c.columns.clone(),
                c.definition.contains("NULLS NOT DISTINCT") || c.kind == ConstraintKind::PrimaryKey,
                c.deferrable,
                c.name.clone(),
            ));
        }
    }
    for i in indexes.iter().filter(|i| i.unique) {
        let Some((keys, nnd)) = expr::index_keys(&i.definition) else {
            untrusted.push(i.name.clone());
            continue;
        };
        let Some(columns) = keys.iter().map(key_column).collect::<Option<Vec<_>>>() else {
            untrusted.push(i.name.clone());
            continue;
        };
        let mut distinct: Vec<String> = Vec::new();
        for c in columns {
            if !distinct.contains(&c) {
                distinct.push(c);
            }
        }
        if !distinct.is_empty() {
            out.push((distinct, nnd, false, i.name.clone()));
        }
    }
    (out, untrusted)
}

fn t_unique_set(
    sets: &[(Vec<String>, bool, bool, String)],
    columns: &[usize],
    cols: &[Col],
) -> bool {
    let names: Vec<&str> = columns.iter().map(|&i| cols[i].name.as_str()).collect();
    sets.iter()
        .any(|(set, ..)| !set.is_empty() && set.iter().all(|s| names.contains(&s.as_str())))
}

/// One table's columns and checks, before keys and sizes.
#[allow(clippy::too_many_lines)]
fn table(e: &Entity, ti: usize, seed: u64, types: &Types, model: &Schema) -> Table {
    let mut columns: Vec<Col> = e
        .columns
        .iter()
        .map(|c| {
            let ty = types.column(c);
            let domain_not_null = ty.domain.as_ref().is_some_and(|d| d.not_null);
            let validate = ty.domain.is_some()
                || !matches!(
                    ty.base,
                    Base::Int2
                        | Base::Int4
                        | Base::Int8
                        | Base::Text
                        | Base::Bool
                        | Base::Uuid
                        | Base::Date
                        | Base::Timestamp { .. }
                        | Base::Float4
                        | Base::Float8
                        | Base::Jsonb
                        | Base::Json
                )
                || ty.array;
            Col {
                name: c.name.clone(),
                type_text: c.r#type.clone(),
                // An array of a NOT NULL domain may itself be NULL.
                not_null: c.not_null || (domain_not_null && !ty.array),
                fill: Fill::Value,
                null_rate: 0.0,
                key: rng::key(seed, &[&e.schema, &e.name, &c.name]),
                heuristic: None,
                bounds: Bounds::default(),
                unique: false,
                disjoint: false,
                stable: false,
                cents: false,
                default: None,
                after: Vec::new(),
                validate,
                domain_checks: Vec::new(),
                identity_always: c.identity == Some(Identity::Always),
                expression: c.generated.as_ref().and(c.default.clone()),
                expression_columns: c
                    .generated
                    .as_ref()
                    .and(c.default.as_deref())
                    .and_then(expr::parse)
                    .map(|x| x.columns())
                    .unwrap_or_default(),
                expression_expr: c
                    .generated
                    .as_ref()
                    .and(c.default.as_deref())
                    .and_then(expr::parse)
                    .filter(checks::evaluable),
                ty,
            }
        })
        .collect();
    let mut fallbacks = Vec::new();
    let mut checks = Vec::new();
    let mut patterns = HashMap::new();
    let mut non_nulls = Vec::new();
    let mut orders: Vec<checks::Order> = Vec::new();
    let col_types: HashMap<String, Type> = columns
        .iter()
        .map(|c| (c.name.clone(), c.ty.clone()))
        .collect();
    let type_of = |name: &str| col_types.get(name).cloned();
    for c in e
        .constraints
        .iter()
        .filter(|c| c.kind == ConstraintKind::Check)
    {
        let parsed = expr::parse_check(&c.definition, false);
        let sql = check_sql(&c.definition);
        let mut shaped = false;
        if let Some(x) = &parsed {
            checks::collect_patterns(x, &mut patterns);
            let s = checks::shapes(x, &c.name, None, &type_of);
            shaped = s.complete;
            for (col, b) in s.bounds {
                if let Some(i) = columns.iter().position(|k| k.name == col) {
                    merge_bounds(&mut columns[i].bounds, b);
                }
            }
            orders.extend(s.orders);
            for nn in s.non_nulls {
                let idx: Option<Vec<usize>> = nn
                    .columns
                    .iter()
                    .map(|n| columns.iter().position(|k| &k.name == n))
                    .collect();
                if let Some(idx) = idx {
                    non_nulls.push(NonNullGroup {
                        columns: idx,
                        min: nn.min,
                        max: nn.max,
                    });
                }
            }
        }
        if !shaped {
            fallbacks.push(match &parsed {
                Some(x) if checks::evaluable(x) => Fallback::new(
                    FallbackKind::Redrawn,
                    Some(c.name.clone()),
                    "evaluated on each row: a row breaking it is drawn again, then dropped by Postgres",
                ),
                _ => Fallback::new(
                    FallbackKind::Judged,
                    Some(c.name.clone()),
                    "judged by Postgres only: rows breaking it are dropped",
                ),
            });
        }
        checks.push(Check {
            name: c.name.clone(),
            sql,
            columns: parsed.as_ref().map(Expr::columns).unwrap_or_default(),
            expr: parsed,
            shaped,
        });
    }
    // Domain CHECKs: VALUE is the column.
    for col in &mut columns {
        let Some(domain) = col.ty.domain.clone() else {
            continue;
        };
        let name = col.name.clone();
        for (definition, parsed) in &domain.checks {
            let Some(x) = parsed else {
                fallbacks.push(Fallback::new(
                    FallbackKind::Judged,
                    Some(definition.clone()),
                    format!(
                        "a CHECK of {name}'s domain this crate cannot read: Postgres judges it"
                    ),
                ));
                continue;
            };
            checks::collect_patterns(x, &mut patterns);
            let label = domain.names.last().cloned().unwrap_or_default();
            let s = checks::shapes(x, &label, Some(&name), &type_of);
            for (column, b) in &s.bounds {
                let b = b.clone();
                if *column == name {
                    merge_bounds(&mut col.bounds, b);
                }
            }
            if !s.complete {
                col.domain_checks.push(x.clone());
            }
        }
    }
    // Orders between columns, from CHECKs and from names.
    let add_order = |cols: &mut [Col], later: usize, earlier: usize, strict: bool| {
        if later != earlier
            && !cols[earlier].after.iter().any(|(c, _)| *c == later)
            && !cols[later].after.iter().any(|(c, _)| *c == earlier)
        {
            cols[later].after.push((earlier, strict));
        }
    };
    for o in &orders {
        let (Some(l), Some(r)) = (
            columns.iter().position(|c| c.name == o.left),
            columns.iter().position(|c| c.name == o.right),
        ) else {
            continue;
        };
        match o.op.as_str() {
            ">" => add_order(&mut columns, l, r, true),
            ">=" => add_order(&mut columns, l, r, false),
            "<" => add_order(&mut columns, r, l, true),
            _ => add_order(&mut columns, r, l, false),
        }
    }
    for (earlier, later) in name_orders(&columns) {
        add_order(&mut columns, later, earlier, false);
    }

    let t_key = rng::key(seed, &[&e.schema, &e.name, "#table"]);
    let staging = format!(
        "t{ti}_{}",
        e.name
            .chars()
            .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
            .take(40)
            .collect::<String>()
            .to_lowercase()
    );
    let leaves = match &e.partition_key {
        Some(key) if e.kind == EntityKind::PartitionedTable => {
            let tree = partition::tree(model, &e.schema, &e.name, key, &|n: &str| {
                col_types.get(n).cloned()
            });
            for s in &tree.skipped {
                fallbacks.push(Fallback::new(
                    FallbackKind::NoRows,
                    Some(s.clone()),
                    "a partition whose bounds are not understood: it gets no rows",
                ));
            }
            tree.leaves
        }
        _ => Vec::new(),
    };
    Table {
        schema: e.schema.clone(),
        name: e.name.clone(),
        role: Role::Entity,
        rows: 0,
        columns,
        fks: Vec::new(),
        checks,
        patterns,
        non_nulls,
        combos: Vec::new(),
        leaf_weights: leaves.iter().map(|l| l.weight).sum(),
        leaves,
        deferrable_unique: e.constraints.iter().any(|c| {
            matches!(
                c.kind,
                ConstraintKind::PrimaryKey | ConstraintKind::Unique | ConstraintKind::Exclusion
            ) && c.deferrable
        }),
        rls_forced: e.rls && e.rls_forced,
        key: t_key,
        perm: Permutation::new(1, &t_key),
        skip: None,
        fallbacks,
        update_key: None,
        sequences: Vec::new(),
        staging,
        bytes_per_row: 0,
        partitioned: e.kind == EntityKind::PartitionedTable,
    }
}

fn merge_bounds(into: &mut Bounds, from: Bounds) {
    checks::merge(into, from);
}

/// `CHECK (expr) [NOT VALID]` → `expr`.
fn check_sql(definition: &str) -> String {
    let d = definition.trim();
    let d = d.strip_suffix("NOT VALID").map_or(d, str::trim_end);
    let d = d.strip_suffix("NO INHERIT").map_or(d, str::trim_end);
    match d.strip_prefix("CHECK") {
        Some(rest) => rest.trim().to_owned(),
        None => d.to_owned(),
    }
}

/// Columns whose names say one comes after another: (earlier, later).
fn name_orders(columns: &[Col]) -> Vec<(usize, usize)> {
    let find = |names: &[&str]| -> Option<usize> {
        names.iter().find_map(|n| {
            columns.iter().position(|c| {
                c.name.eq_ignore_ascii_case(n) && (c.ty.is_temporal() || c.ty.is_numeric())
            })
        })
    };
    let pairs: &[(&[&str], &[&str])] = &[
        (
            &["created_at", "created", "created_on", "inserted_at"],
            &["updated_at", "modified_at", "updated", "updated_on"],
        ),
        (
            &["created_at", "created_on"],
            &[
                "deleted_at",
                "archived_at",
                "closed_at",
                "completed_at",
                "resolved_at",
                "cancelled_at",
                "canceled_at",
                "published_at",
                "last_login_at",
                "last_seen_at",
            ],
        ),
        (
            &[
                "starts_at",
                "start_at",
                "started_at",
                "start_time",
                "starts_on",
                "start_date",
                "begins_at",
                "valid_from",
                "from_date",
                "check_in",
            ],
            &[
                "ends_at",
                "end_at",
                "ended_at",
                "end_time",
                "ends_on",
                "end_date",
                "finished_at",
                "valid_to",
                "valid_until",
                "to_date",
                "check_out",
            ],
        ),
        (
            &["issued_on", "issued_at", "invoiced_at"],
            &["due_on", "due_at", "paid_at"],
        ),
        (
            &["placed_at", "ordered_at"],
            &["shipped_at", "delivered_at"],
        ),
        (&["shipped_at"], &["delivered_at"]),
        (
            &["min_price", "min_amount", "min_value", "minimum"],
            &["max_price", "max_amount", "max_value", "maximum"],
        ),
    ];
    let mut out = Vec::new();
    for (earlier, later) in pairs {
        let Some(e) = find(earlier) else { continue };
        for l in *later {
            if let Some(li) = find(&[*l])
                && li != e
            {
                out.push((e, li));
            }
        }
    }
    out
}

/// Breaks cycles; returns units in load order and the deferred FKs.
fn order(tables: &[Table]) -> (Vec<Unit>, Vec<(usize, usize)>) {
    let n = tables.len();
    let edges: Vec<Vec<usize>> = tables
        .iter()
        .enumerate()
        .map(|(i, t)| {
            let mut e: Vec<usize> = t
                .fks
                .iter()
                .filter_map(|f| f.parent)
                .filter(|&p| p != i)
                .collect();
            e.sort_unstable();
            e.dedup();
            e
        })
        .collect();
    let sccs = tarjan(n, &edges);
    let mut units = Vec::new();
    let mut deferred = Vec::new();
    for scc in sccs {
        if scc.len() == 1 {
            units.push(Unit {
                tables: scc,
                held: Vec::new(),
            });
            continue;
        }
        // NOT NULL edges must point at tables loaded before; find an order
        // keeping as many as possible, nullable edges going backwards are
        // deferred, and a NOT NULL cycle has one FK held back.
        let members: HashSet<usize> = scc.iter().copied().collect();
        let mut hard: Vec<(usize, usize, usize)> = Vec::new(); // (child, fk, parent)
        for &c in &scc {
            for (fi, f) in tables[c].fks.iter().enumerate() {
                if let Some(p) = f.parent
                    && p != c
                    && members.contains(&p)
                    && !f.nullable
                {
                    hard.push((c, fi, p));
                }
            }
        }
        let mut held: Vec<(usize, usize)> = Vec::new();
        let ordered = loop {
            let active: Vec<&(usize, usize, usize)> = hard
                .iter()
                .filter(|(c, f, _)| !held.contains(&(*c, *f)))
                .collect();
            let mut placed: Vec<usize> = Vec::new();
            let mut left: Vec<usize> = scc.clone();
            left.sort_unstable();
            while !left.is_empty() {
                let ready = left.iter().position(|&t| {
                    active
                        .iter()
                        .filter(|(c, ..)| *c == t)
                        .all(|(_, _, p)| placed.contains(p))
                });
                match ready {
                    Some(i) => placed.push(left.remove(i)),
                    None => break,
                }
            }
            if left.is_empty() {
                break placed;
            }
            // Hold back one FK of the cycle: a deferrable one if any.
            let stuck: Vec<&&(usize, usize, usize)> = active
                .iter()
                .filter(|(c, _, p)| left.contains(c) && left.contains(p))
                .collect();
            let pick = stuck
                .iter()
                .find(|(c, f, _)| tables[*c].fks[*f].definition.contains("DEFERRABLE"))
                .or_else(|| stuck.first())
                .map(|(c, f, _)| (*c, *f));
            match pick {
                Some(p) => held.push(p),
                None => break placed.into_iter().chain(left).collect(),
            }
        };
        let position: HashMap<usize, usize> =
            ordered.iter().enumerate().map(|(i, &t)| (t, i)).collect();
        for &c in &ordered {
            for (fi, f) in tables[c].fks.iter().enumerate() {
                if let Some(p) = f.parent
                    && p != c
                    && members.contains(&p)
                    && position[&p] > position[&c]
                    && f.nullable
                {
                    deferred.push((c, fi));
                }
            }
        }
        units.push(Unit {
            tables: ordered,
            held,
        });
    }
    (units, deferred)
}

/// Strongly connected components, each emitted after those it points at
/// (parents before children).
fn tarjan(n: usize, edges: &[Vec<usize>]) -> Vec<Vec<usize>> {
    struct State {
        index: Vec<Option<usize>>,
        low: Vec<usize>,
        on_stack: Vec<bool>,
        stack: Vec<usize>,
        next: usize,
        out: Vec<Vec<usize>>,
    }
    fn visit(v: usize, edges: &[Vec<usize>], s: &mut State) {
        s.index[v] = Some(s.next);
        s.low[v] = s.next;
        s.next += 1;
        s.stack.push(v);
        s.on_stack[v] = true;
        for &w in &edges[v] {
            match s.index[w] {
                None => {
                    visit(w, edges, s);
                    s.low[v] = s.low[v].min(s.low[w]);
                }
                Some(iw) if s.on_stack[w] => s.low[v] = s.low[v].min(iw),
                Some(_) => {}
            }
        }
        if Some(s.low[v]) == s.index[v] {
            let mut scc = Vec::new();
            while let Some(w) = s.stack.pop() {
                s.on_stack[w] = false;
                scc.push(w);
                if w == v {
                    break;
                }
            }
            scc.sort_unstable();
            s.out.push(scc);
        }
    }
    let mut s = State {
        index: vec![None; n],
        low: vec![0; n],
        on_stack: vec![false; n],
        stack: Vec::new(),
        next: 0,
        out: Vec::new(),
    };
    for v in 0..n {
        if s.index[v].is_none() {
            visit(v, edges, &mut s);
        }
    }
    s.out
}

/// How each column of table `ti` is filled: keys, foreign keys,
/// partitions, heuristics, unique sets.
#[allow(clippy::too_many_lines)]
fn fill_columns(
    tables: &mut [Table],
    ti: usize,
    e: &Entity,
    referenced: &HashSet<(usize, usize)>,
    options: &Options,
) {
    let profile = options.profile;
    let base_null = match profile {
        Profile::Realistic => 0.1,
        Profile::EdgeCases => 0.4,
    };
    let (sets, untrusted) = t_sets(&e.constraints, &e.indexes);
    for name in untrusted {
        tables[ti].fallbacks.push(Fallback::new(
            FallbackKind::Judged,
            Some(name),
            "a unique index on an expression the generator cannot keep distinct: duplicates are dropped by the load",
        ));
    }
    let has_deferred = tables[ti].fks.iter().any(|f| f.deferred);
    // The key a cycle UPDATE finds rows by: the PK, else a NOT NULL unique.
    let update_key: Option<Vec<usize>> = if has_deferred {
        let t = &tables[ti];
        sets.iter()
            .filter_map(|(cols, ..)| cols.iter().map(|n| t.column(n)).collect::<Option<Vec<_>>>())
            .find(|idx| {
                idx.iter().all(|&i| {
                    t.columns[i].not_null
                        && !t.fks.iter().any(|f| f.deferred && f.columns.contains(&i))
                })
            })
    } else {
        None
    };
    let mut must_write: HashSet<usize> = referenced
        .iter()
        .filter(|(t, _)| *t == ti)
        .map(|(_, c)| *c)
        .collect();
    if let Some(k) = &update_key {
        must_write.extend(k.iter().copied());
    }
    if has_deferred && update_key.is_none() {
        tables[ti].fallbacks.push(Fallback::new(
            FallbackKind::NotBuilt,
            None,
            "no primary key or NOT NULL unique to fill the cycle's foreign keys by: they stay NULL",
        ));
        for f in &mut tables[ti].fks {
            if f.deferred {
                f.null_rate = 1.0;
            }
        }
    }
    tables[ti].update_key = update_key;

    // Foreign keys first: a column assigned by the widest FK covering it.
    let mut fk_order: Vec<usize> = (0..tables[ti].fks.len()).collect();
    fk_order.sort_by_key(|&f| std::cmp::Reverse(tables[ti].fks[f].columns.len()));
    let mut assigned: HashMap<usize, (usize, usize)> = HashMap::new();
    for &f in &fk_order {
        let fk = &tables[ti].fks[f];
        if fk.columns.iter().all(|c| assigned.contains_key(c)) {
            continue;
        }
        for (pos, &c) in fk.columns.iter().enumerate() {
            assigned.entry(c).or_insert((f, pos));
        }
    }
    let partition_columns: HashSet<String> = tables[ti]
        .leaves
        .iter()
        .flat_map(|l| l.keys.iter().map(|(c, _)| c.clone()))
        .collect();

    let table_name = tables[ti].name.clone();
    let mut skip = None;
    for (ci, c) in e.columns.iter().enumerate() {
        let col = &mut tables[ti].columns[ci];
        col.null_rate = if col.not_null { 0.0 } else { base_null };
        if col.bounds.not_null {
            col.not_null = true;
            col.null_rate = 0.0;
        }
        if col.bounds.prefer_not_null {
            col.null_rate = 0.0;
        }
        let sequence = c.identity.is_some() || c.default.as_deref().and_then(nextval).is_some();
        if c.generated.is_some() {
            col.fill = Fill::Database(match c.generated {
                Some(Generated::Virtual) => "a virtual generated column",
                _ => "a generated column",
            });
            continue;
        }
        if sequence {
            if must_write.contains(&ci) && col.ty.is_integer() {
                col.fill = Fill::Sequence { start: 1 };
                col.stable = true;
                col.unique = true;
                let seq = c.default.as_deref().and_then(nextval).flatten();
                tables[ti].sequences.push((ci, seq));
            } else {
                col.fill = Fill::Database(if c.identity.is_some() {
                    "an identity column"
                } else {
                    "a serial column"
                });
            }
            continue;
        }
        if let Some(&(f, pos)) = assigned.get(&ci) {
            col.fill = Fill::Foreign {
                fk: f,
                position: pos,
            };
            continue;
        }
        if partition_columns.contains(&c.name) {
            col.fill = Fill::Partition;
            col.stable = true;
            continue;
        }
        if matches!(col.ty.base, Base::Unknown(_)) {
            if col.not_null && c.default.is_none() {
                skip = Some(format!(
                    "column {} has a type the generator cannot produce ({})",
                    c.name, c.r#type
                ));
            }
            if col.not_null && c.default.is_some() {
                col.fill = Fill::Database("a type the generator cannot produce: its default");
            } else {
                col.fill = Fill::Null;
            }
            continue;
        }
        col.heuristic = heuristics::choose(&table_name, &c.name, &col.ty);
        if let Some(h) = col.heuristic
            && let Some(rate) = h.null_rate()
            && !col.not_null
        {
            col.null_rate = rate;
        }
        if !col.not_null && must_write.contains(&ci) {
            col.null_rate = 0.0;
        }
        let lname = c.name.to_lowercase();
        col.cents = lname.contains("cent")
            || col
                .ty
                .domain
                .as_ref()
                .is_some_and(|d| d.names.iter().any(|n| n.contains("cent")));
        let default =
            c.default
                .as_deref()
                .or(col.ty.domain.as_ref().and_then(|d| d.default.as_deref()));
        if let Some(d) = default
            && let Some(x) = expr::parse(d)
        {
            col.default = default_value(&x, &col.ty);
        }
        if must_write.contains(&ci) {
            col.stable = true;
        }
    }
    if let Some(reason) = skip {
        tables[ti].skip = Some(reason);
    }

    // Unique sets: one column injective, or the set drawn as a combination.
    let mut in_combo: HashSet<usize> = HashSet::new();
    // Foreign keys reaching into a NULLS NOT DISTINCT set: never NULL.
    let mut never_null_fks: HashSet<usize> = HashSet::new();
    for (names, nnd, deferrable, set_name) in &sets {
        let Some(idx) = names
            .iter()
            .map(|n| tables[ti].column(n))
            .collect::<Option<Vec<usize>>>()
        else {
            continue;
        };
        // NULLS NOT DISTINCT: two NULLs collide, in whichever column keeps
        // the set apart, so none of its columns is NULL; whatever made it
        // distinct already (another set, a sequence, a 1:1 key).
        if *nnd {
            for &i in &idx {
                tables[ti].columns[i].null_rate = 0.0;
            }
            for (f, fk) in tables[ti].fks.iter().enumerate() {
                if fk.columns.iter().any(|c| idx.contains(c)) {
                    never_null_fks.insert(f);
                }
            }
        }
        let t = &tables[ti];
        let _ = deferrable;
        // Already unique: a sequence, identity, uuid, an injective column,
        // a 1:1 foreign key.
        let done = idx.iter().any(|&i| {
            let col = &t.columns[i];
            col.unique
                || matches!(col.fill, Fill::Database(d) if d.contains("identity") || d.contains("serial"))
                || (matches!(col.fill, Fill::Value) && col.ty.base == Base::Uuid && !col.ty.array)
        });
        if done {
            continue;
        }
        // One-to-one: a foreign key whose columns are this set.
        let one_to_one = t.fks.iter().position(|f| {
            f.columns.len() == idx.len()
                && f.columns.iter().all(|c| idx.contains(c))
                && f.parent.is_some()
                && f.parent != Some(ti)
        });
        if let Some(f) = one_to_one {
            tables[ti].fks[f].mode = FkMode::OneToOne;
            continue;
        }
        // A column to make injective.
        let candidate = idx.iter().copied().find(|&i| {
            let col = &t.columns[i];
            matches!(col.fill, Fill::Value)
                && col.ty.can_be_unique()
                && col.bounds.allowed.is_none()
        });
        if let Some(i) = candidate {
            let col = &mut tables[ti].columns[i];
            col.unique = true;
            if !*nnd && col.null_rate > 0.0 && idx.len() == 1 {
                // NULLs never collide, but keys read better complete.
                col.null_rate = col.null_rate.min(0.05);
            }
            continue;
        }
        // A combination of foreign keys and small domains.
        let mut parts = Vec::new();
        let mut ok = true;
        let mut fks_used = Vec::new();
        for &i in &idx {
            if in_combo.contains(&i) {
                ok = false;
                break;
            }
            let col = &t.columns[i];
            match col.fill {
                Fill::Foreign { fk, .. } => {
                    if !fks_used.contains(&fk)
                        && !matches!(t.fks[fk].mode, FkMode::Combo { .. })
                        && t.fks[fk].parent.is_some_and(|p| p != ti)
                    {
                        fks_used.push(fk);
                        parts.push(ComboPart::Fk(fk));
                    } else if !fks_used.contains(&fk) {
                        ok = false;
                    }
                }
                Fill::Value => {
                    let values: Option<Vec<V>> = match (&col.bounds.allowed, &col.ty.base) {
                        (Some(a), _) => Some(a.clone()),
                        (None, Base::Enum { labels, .. }) if !col.ty.array => {
                            Some(labels.iter().map(|l| V::Text(l.clone())).collect())
                        }
                        (None, Base::Bool) if !col.ty.array => {
                            Some(vec![V::Bool(false), V::Bool(true)])
                        }
                        _ => None,
                    };
                    match values {
                        Some(v) if !v.is_empty() => parts.push(ComboPart::Column {
                            column: i,
                            values: v,
                        }),
                        _ => ok = false,
                    }
                }
                _ => ok = false,
            }
        }
        if ok && !parts.is_empty() {
            let combo = tables[ti].combos.len();
            for (pi, part) in parts.iter().enumerate() {
                match part {
                    ComboPart::Fk(f) => tables[ti].fks[*f].mode = FkMode::Combo { combo, part: pi },
                    ComboPart::Column { column, .. } => {
                        in_combo.insert(*column);
                        tables[ti].columns[*column].null_rate = 0.0;
                    }
                }
            }
            for &i in &idx {
                in_combo.insert(i);
            }
            let key = tables[ti].key;
            tables[ti].combos.push(Combo {
                parts,
                space: 0,
                perm: Permutation::new(1, &key),
            });
        } else {
            tables[ti].fallbacks.push(Fallback::new(
                FallbackKind::NotBuilt,
                Some(set_name.clone()),
                "no column here can be made distinct row by row: duplicates are dropped by the load",
            ));
        }
    }

    // Exclusion constraints: `&&` columns never overlap; `=` only sets are
    // unique sets (covered above when they are constraints).
    for c in e
        .constraints
        .iter()
        .filter(|c| c.kind == ConstraintKind::Exclusion)
    {
        let Some(elements) = expr::exclusion_elements(&c.definition) else {
            tables[ti].fallbacks.push(Fallback::new(
                FallbackKind::Judged,
                Some(c.name.clone()),
                "an exclusion constraint not understood: rows it refuses are dropped",
            ));
            continue;
        };
        let mut handled = false;
        for (x, op) in &elements {
            if op == "&&"
                && let Expr::Col(name) = x
                && let Some(i) = tables[ti].column(name)
                && matches!(tables[ti].columns[i].fill, Fill::Value)
            {
                tables[ti].columns[i].disjoint = true;
                handled = true;
            }
        }
        if !handled && elements.iter().all(|(_, op)| op == "=") {
            let names: Vec<String> = elements
                .iter()
                .filter_map(|(x, _)| match x {
                    Expr::Col(n) => Some(n.clone()),
                    _ => None,
                })
                .collect();
            if let Some(i) = names
                .iter()
                .find_map(|n| tables[ti].column(n))
                .filter(|&i| {
                    matches!(tables[ti].columns[i].fill, Fill::Value)
                        && tables[ti].columns[i].ty.can_be_unique()
                })
            {
                tables[ti].columns[i].unique = true;
                handled = true;
            }
        }
        if !handled {
            tables[ti].fallbacks.push(Fallback::new(
                FallbackKind::Judged,
                Some(c.name.clone()),
                "an exclusion constraint the generator does not build: rows it refuses are dropped",
            ));
        }
    }

    // NULL shares of foreign keys.
    for (fi, f) in tables[ti].fks.iter_mut().enumerate() {
        if f.null_rate < 1.0 {
            f.null_rate = if f.nullable
                && !matches!(f.mode, FkMode::Combo { .. })
                && !never_null_fks.contains(&fi)
            {
                match f.mode {
                    FkMode::Tree | FkMode::Chain => 0.05,
                    _ => base_null,
                }
            } else {
                0.0
            };
        }
        f.stable = f.columns.iter().any(|&c| must_write.contains(&c));
    }
    for f in 0..tables[ti].fks.len() {
        let stable = tables[ti].fks[f].stable;
        if stable {
            for c in tables[ti].fks[f].columns.clone() {
                tables[ti].columns[c].stable = true;
            }
        }
    }
    tables[ti].bytes_per_row = 24 + tables[ti].columns.iter().map(width).sum::<u64>();
}

/// A guess of a value's size on disk, for the byte estimate.
fn width(c: &Col) -> u64 {
    if !c.written() {
        return 8;
    }
    let base = match &c.ty.base {
        Base::Int2 => 2,
        Base::Int4 | Base::Float4 | Base::Date => 4,
        Base::Int8 | Base::Float8 | Base::Timestamp { .. } | Base::Money | Base::Time { .. } => 8,
        Base::Uuid | Base::Interval => 16,
        Base::Bool | Base::InternalChar => 1,
        Base::Vector { dims, .. } => 8 + 4 * u64::from(dims.unwrap_or(3)),
        Base::Geometry { .. } => 60,
        Base::Json | Base::Jsonb => 80,
        Base::Char(n) | Base::Varchar(Some(n)) => u64::from(*n).min(64) + 1,
        _ => 24,
    };
    let base = match c.heuristic {
        Some(Heuristic::Paragraph) => 200,
        Some(Heuristic::Sentence) => 60,
        Some(Heuristic::UserAgent) => 110,
        _ => base,
    };
    if c.ty.array { base * 2 + 24 } else { base }
}

/// Caps a table's rows by what its keys and foreign keys can hold.
fn cap_rows(tables: &mut [Table], ti: usize) {
    let mut cap = tables[ti].rows;
    let mut reasons: Vec<(Option<String>, String)> = Vec::new();
    if tables[ti].skip.is_some() {
        tables[ti].rows = 0;
        return;
    }
    // NOT NULL foreign keys to tables without rows.
    for f in &tables[ti].fks {
        let parent_rows = f.parent.map_or(0, |p| {
            if tables[p].skip.is_some() {
                0
            } else {
                tables[p].rows
            }
        });
        if !f.nullable && parent_rows == 0 && f.parent != Some(ti) {
            cap = 0;
            let why = match f.parent {
                Some(p) => format!("references {}, which gets no rows", tables[p].qualified()),
                None => "references a table outside what is loaded".to_owned(),
            };
            reasons.push((Some(f.name.clone()), why));
        }
        if f.mode == FkMode::OneToOne && parent_rows < cap {
            cap = parent_rows;
            reasons.push((
                Some(f.name.clone()),
                "one row per parent at most".to_owned(),
            ));
        }
    }
    // Unique columns and keys.
    for c in &tables[ti].columns {
        if c.unique
            && let Some(n) = generate::capacity(&c.ty, &c.bounds)
            && n < cap
        {
            cap = n;
            reasons.push((
                Some(c.name.clone()),
                format!("only {n} distinct values fit the column"),
            ));
        }
    }
    // Combinations.
    let space: Vec<u64> = tables[ti]
        .combos
        .iter()
        .map(|combo| {
            combo
                .parts
                .iter()
                .map(|p| p.radix(tables, &tables[ti].fks))
                .try_fold(1u64, u64::checked_mul)
                .unwrap_or(u64::MAX)
        })
        .collect();
    for (k, s) in space.iter().enumerate() {
        tables[ti].combos[k].space = *s;
        if *s < cap {
            cap = *s;
            reasons.push((
                None,
                format!("only {s} distinct combinations of its unique columns"),
            ));
        }
    }
    // Partitioned without a leaf rows can land in.
    if tables[ti].partitioned && tables[ti].leaves.is_empty() {
        cap = 0;
        reasons.push((None, "no partition whose bounds are understood".to_owned()));
    }
    if cap < tables[ti].rows {
        for (constraint, reason) in reasons {
            tables[ti].fallbacks.push(Fallback::new(
                FallbackKind::Capped,
                constraint,
                format!("rows capped at {cap}: {reason}"),
            ));
        }
        tables[ti].rows = cap;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tarjan_puts_parents_first() {
        // 0 → 1 → 2, and 3 ⇄ 4 → 2
        let edges = vec![vec![1], vec![2], vec![], vec![4], vec![3, 2]];
        let sccs = tarjan(5, &edges);
        let pos = |t: usize| sccs.iter().position(|s| s.contains(&t)).unwrap();
        assert!(pos(2) < pos(1) && pos(1) < pos(0));
        assert!(pos(2) < pos(3));
        assert_eq!(pos(3), pos(4));
    }

    #[test]
    fn check_sql_strips_the_keyword() {
        assert_eq!(check_sql("CHECK ((a > 0)) NOT VALID"), "((a > 0))");
    }

    #[test]
    fn nextval_names_its_sequence() {
        assert_eq!(
            nextval("nextval('public.t_id_seq'::regclass)"),
            Some(Some("public.t_id_seq".to_owned()))
        );
        assert_eq!(nextval("now()"), None);
    }
}

#[test]
fn every_skipped_form_is_one_note_and_the_model_stays() {
    let mut failures = Vec::new();
    for (case, words) in CASES {
        let compiled = common::compile(&format!("{BASE}{case}"));
        let notes: Vec<_> = compiled
            .diagnostics
            .iter()
            .map(|d| (d.severity, d.code, d.message.as_str()))
            .collect();
        let expected = format!("{words} is not supported in the browser preview.");
        let one_note = matches!(
            notes.as_slice(),
            [(Severity::Info, Code::NotRun, message)] if *message == expected
        );
        if !one_note || compiled.model.is_none() {
            failures.push(format!("{case}\n  wanted: {expected}\n  got: {notes:?}"));
        }
    }
    assert!(failures.is_empty(), "\n{}", failures.join("\n"));
}

#[test]
fn a_note_says_where_the_app_compiles_it() {
    let compiled = common::compile("CREATE SEQUENCE s; ALTER SEQUENCE s RESTART;");
    let [note] = compiled.diagnostics.as_slice() else {
        panic!("one note: {:?}", compiled.diagnostics);
    };
    assert_eq!(
        note.hint.as_deref(),
        Some("Here it is skipped; the app compiles it in a real Postgres.")
    );
    assert_eq!(note.statement, Some(1));
    let span = note.span.expect("located");
    assert_eq!(span.start, "CREATE SEQUENCE s; ".len());
}

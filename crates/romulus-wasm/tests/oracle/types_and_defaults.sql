CREATE SCHEMA billing;
CREATE TYPE billing.x_status AS ENUM ('a');
CREATE TYPE mood AS ENUM ('sad', 'ok');
ALTER TYPE mood ADD VALUE 'happy';
ALTER TYPE mood ADD VALUE 'meh' BEFORE 'ok';
CREATE DOMAIN email AS text NOT NULL CHECK (VALUE ~ '@') DEFAULT 'a@b';
CREATE DOMAIN positive AS numeric(10,2) CONSTRAINT positive_check CHECK (VALUE > 0);
CREATE TYPE pair AS (a int, b text, c numeric(5,1));
COMMENT ON TYPE mood IS 'How it feels';
CREATE TABLE t (
  a serial,
  b bigserial PRIMARY KEY,
  c smallint GENERATED BY DEFAULT AS IDENTITY,
  d varchar, e char(3), f numeric, g timestamp(3), h time, i interval, j float, k real, l double precision,
  m json, n jsonb DEFAULT '{}', o bytea, p inet, q float8, r int2, s decimal(8,3), u timestamptz(0), v bit(4), w varbit, x date, y money, z uuid,
  aa text[] DEFAULT ARRAY[]::text[], ab int[] DEFAULT '{1,2}', ac int DEFAULT -1, ad bigint DEFAULT 0, ae bigint DEFAULT 0::bigint,
  af timestamptz DEFAULT CURRENT_TIMESTAMP, ag date DEFAULT CURRENT_DATE, ah timestamptz DEFAULT now() + interval '1 day',
  ai varchar(10) DEFAULT 'a', aj boolean DEFAULT true, ak numeric DEFAULT 1.5, al numeric(4,1) DEFAULT 2,
  am mood DEFAULT 'ok', an email, ao positive, ap pair, aq billing.x_status, ar text COLLATE "C",
  "Weird Name" int, at character varying(5)[], au int GENERATED ALWAYS AS (ac * 2) STORED,
  av bigint DEFAULT 5000000000, aw text DEFAULT ''
);

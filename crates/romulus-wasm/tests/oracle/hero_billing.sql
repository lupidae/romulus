-- The hero's schema, then what a visitor typically types into it.
CREATE TYPE invoice_status AS ENUM ('draft', 'open', 'paid', 'void');

CREATE TABLE customers (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email      text NOT NULL UNIQUE,
  name       text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE customers IS 'People and companies we bill';

CREATE TABLE plans (
  id          smallint PRIMARY KEY,
  name        text NOT NULL,
  price_cents integer NOT NULL CHECK (price_cents >= 0)
);

CREATE TABLE subscriptions (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  customer_id uuid NOT NULL REFERENCES customers ON DELETE CASCADE,
  plan_id     smallint NOT NULL REFERENCES plans,
  started_at  date NOT NULL DEFAULT CURRENT_DATE,
  ends_at     date,
  CHECK (ends_at IS NULL OR ends_at > started_at)
);

CREATE TABLE invoices (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id     uuid NOT NULL REFERENCES customers ON DELETE CASCADE,
  subscription_id bigint REFERENCES subscriptions,
  status          invoice_status NOT NULL DEFAULT 'draft',
  total_cents     bigint NOT NULL DEFAULT 0 CHECK (total_cents >= 0),
  issued_at       timestamptz
);
CREATE INDEX invoices_customer_id_idx ON invoices (customer_id);
CREATE INDEX invoices_open_idx ON invoices (issued_at) WHERE status = 'open';
COMMENT ON COLUMN invoices.total_cents IS 'Sum of the lines, in cents';

CREATE TABLE invoice_lines (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  invoice_id  uuid NOT NULL REFERENCES invoices ON DELETE CASCADE,
  description text NOT NULL,
  quantity    integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
  unit_cents  bigint NOT NULL
);

CREATE TABLE payments (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  invoice_id  uuid NOT NULL REFERENCES invoices,
  amount      numeric(12, 2) NOT NULL CHECK (amount > 0),
  method      varchar(20) NOT NULL CHECK (method IN ('card', 'transfer', 'cash')),
  paid_at     timestamptz NOT NULL DEFAULT now()
);

-- Edits.
ALTER TABLE customers ADD COLUMN phone text;
ALTER TABLE customers ADD COLUMN country char(2) NOT NULL DEFAULT 'FR';
ALTER TABLE invoices ADD COLUMN due_at timestamptz DEFAULT now() + interval '30 days';
ALTER TABLE payments RENAME COLUMN amount TO amount_paid;
ALTER TABLE payments ADD CONSTRAINT payments_invoice_unique UNIQUE (invoice_id, paid_at);
ALTER TYPE invoice_status ADD VALUE 'refunded' AFTER 'paid';
CREATE TABLE refunds (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id bigint NOT NULL REFERENCES payments,
  reason     text,
  at         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE VIEW open_invoices AS
  SELECT i.id, c.email, i.total_cents, i.issued_at
  FROM invoices i JOIN customers c ON c.id = i.customer_id
  WHERE i.status = 'open';
ALTER TABLE plans RENAME TO price_plans;
